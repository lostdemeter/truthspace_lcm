#!/usr/bin/env python3
"""
Gear Blend Projection

The key insight from quaternion analysis:
- Different sentence structures produce DIFFERENT quaternion signatures
- We can use quaternion SLERP to BLEND between structures
- The gear ratio controls HOW MUCH we blend toward signal style

Instead of picking one structure, we:
1. Encode truth as quaternion
2. Find nearest signal quaternions
3. SLERP between truth and signal quaternions
4. Use the blended quaternion to weight output choices

This is true geometric blending - not template selection.

Author: Lesley Gushurst
License: GPLv3
"""

import os
import sys
import json
import re
import math
from typing import Dict, List, Tuple, Optional
from collections import Counter, defaultdict
from dataclasses import dataclass

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from truthspace_lcm.core.geometric import GeometricQA


@dataclass
class Quaternion:
    """A quaternion q = w + xi + yj + zk"""
    w: float
    x: float
    y: float
    z: float
    
    def __mul__(self, other: 'Quaternion') -> 'Quaternion':
        return Quaternion(
            w=self.w*other.w - self.x*other.x - self.y*other.y - self.z*other.z,
            x=self.w*other.x + self.x*other.w + self.y*other.z - self.z*other.y,
            y=self.w*other.y - self.x*other.z + self.y*other.w + self.z*other.x,
            z=self.w*other.z + self.x*other.y - self.y*other.x + self.z*other.w,
        )
    
    def conjugate(self) -> 'Quaternion':
        return Quaternion(self.w, -self.x, -self.y, -self.z)
    
    def norm(self) -> float:
        return math.sqrt(self.w**2 + self.x**2 + self.y**2 + self.z**2)
    
    def normalize(self) -> 'Quaternion':
        n = self.norm()
        if n < 1e-10:
            return Quaternion(1, 0, 0, 0)
        return Quaternion(self.w/n, self.x/n, self.y/n, self.z/n)
    
    def dot(self, other: 'Quaternion') -> float:
        return self.w*other.w + self.x*other.x + self.y*other.y + self.z*other.z
    
    def slerp(self, other: 'Quaternion', t: float) -> 'Quaternion':
        """Spherical linear interpolation."""
        q1 = self.normalize()
        q2 = other.normalize()
        
        dot = q1.dot(q2)
        if dot < 0:
            q2 = Quaternion(-q2.w, -q2.x, -q2.y, -q2.z)
            dot = -dot
        
        if dot > 0.9995:
            result = Quaternion(
                q1.w + t*(q2.w - q1.w),
                q1.x + t*(q2.x - q1.x),
                q1.y + t*(q2.y - q1.y),
                q1.z + t*(q2.z - q1.z),
            )
            return result.normalize()
        
        theta_0 = math.acos(min(1, max(-1, dot)))
        theta = theta_0 * t
        
        sin_theta = math.sin(theta)
        sin_theta_0 = math.sin(theta_0)
        
        if abs(sin_theta_0) < 1e-10:
            return q1
        
        s1 = math.cos(theta) - dot * sin_theta / sin_theta_0
        s2 = sin_theta / sin_theta_0
        
        return Quaternion(
            s1*q1.w + s2*q2.w,
            s1*q1.x + s2*q2.x,
            s1*q1.y + s2*q2.y,
            s1*q1.z + s2*q2.z,
        )
    
    @staticmethod
    def identity() -> 'Quaternion':
        return Quaternion(1, 0, 0, 0)


class GearBlendProjector:
    """
    Projects using quaternion gear blending.
    
    The gear metaphor:
    - Truth gear: encodes input as quaternion
    - Signal gear: collection of signal quaternions
    - Meshing: SLERP interpolation between truth and nearest signals
    - Ratio: controls blend amount (0 = pure truth, 1 = pure signal)
    
    Output is generated by using the blended quaternion to weight
    choices at each decision point in sentence construction.
    """
    
    def __init__(self, truth_corpus_path: str, signal_corpus_path: str):
        self.truth_qa = GeometricQA()
        self.truth_qa.load_corpus(truth_corpus_path)
        self.truth_qa.set_output_lens('natural')
        
        # Load signal corpus
        self.signal_frames = {}
        signal_texts = []
        if os.path.exists(signal_corpus_path):
            with open(signal_corpus_path, 'r') as f:
                data = json.load(f)
                for frame in data.get('frames', []):
                    agent = frame.get('agent', '').lower()
                    text = frame.get('text', '')
                    if agent and text:
                        self.signal_frames[agent] = text
                        signal_texts.append(text)
        
        # Learn word quaternions
        self.word_q = self._learn_word_quaternions(signal_texts)
        
        # Index signals by quaternion
        self.signal_index = []
        for agent, text in self.signal_frames.items():
            q = self._encode_sentence(text)
            self.signal_index.append((q, text, agent))
        
        # Learn style quaternions for different structures
        self.style_quaternions = self._learn_style_quaternions()
        
        print(f"Learned {len(self.word_q)} word quaternions")
        print(f"Indexed {len(self.signal_index)} signals")
        print(f"Learned {len(self.style_quaternions)} style patterns")
    
    def _learn_word_quaternions(self, texts: List[str]) -> Dict[str, Quaternion]:
        """Learn quaternion encoding for each word."""
        freq = Counter()
        positions = defaultdict(list)
        
        for text in texts:
            words = re.findall(r'\b\w+\b', text.lower())
            if not words:
                continue
            freq.update(words)
            for i, w in enumerate(words):
                positions[w].append(i / len(words))
        
        max_freq = max(freq.values()) if freq else 1
        word_q = {}
        
        for word in freq:
            f = freq[word] / max_freq
            avg_pos = sum(positions[word]) / len(positions[word])
            
            # Encode word properties as quaternion components
            w_comp = f  # Frequency
            x_comp = avg_pos * 2 - 1  # Position [-1, 1]
            y_comp = 0.8 if word.endswith('ing') else (-0.3 if not word.endswith('s') else 0.3)
            z_comp = 0.5 if word in {'who', 'that', 'which'} else 0.0
            
            word_q[word] = Quaternion(w_comp, x_comp, y_comp, z_comp).normalize()
        
        return word_q
    
    def _encode_sentence(self, text: str) -> Quaternion:
        """Encode sentence as quaternion by composing word quaternions."""
        words = re.findall(r'\b\w+\b', text.lower())
        if not words:
            return Quaternion.identity()
        
        result = Quaternion.identity()
        for w in words:
            if w in self.word_q:
                result = result * self.word_q[w]
            else:
                result = result * Quaternion(0.9, 0.1, 0.0, 0.0).normalize()
        
        return result.normalize()
    
    def _learn_style_quaternions(self) -> Dict[str, Quaternion]:
        """Learn quaternion signatures for different sentence styles."""
        styles = {
            'formal': [],      # "X is a Y that..."
            'informal': [],    # "X seems to be..."
            'active': [],      # "X who does..."
            'passive': [],     # "X that involves..."
        }
        
        for text in self.signal_frames.values():
            text_lower = text.lower()
            q = self._encode_sentence(text)
            
            if 'is a' in text_lower and 'seems' not in text_lower:
                styles['formal'].append(q)
            if 'seems to be' in text_lower or 'seems like' in text_lower:
                styles['informal'].append(q)
            if ' who ' in text_lower:
                styles['active'].append(q)
            if 'involves' in text_lower or 'that' in text_lower:
                styles['passive'].append(q)
        
        # Compute centroid quaternion for each style
        style_q = {}
        for style, qs in styles.items():
            if qs:
                # Average quaternion (simple mean, then normalize)
                avg = Quaternion(
                    sum(q.w for q in qs) / len(qs),
                    sum(q.x for q in qs) / len(qs),
                    sum(q.y for q in qs) / len(qs),
                    sum(q.z for q in qs) / len(qs),
                )
                style_q[style] = avg.normalize()
        
        return style_q
    
    def project(self, concept: str, blend_ratio: float = 0.7) -> str:
        """
        Project truth to signal using quaternion blending.
        
        blend_ratio: 0 = pure truth style, 1 = pure signal style
        """
        concept_lower = concept.lower()
        
        truth = self.truth_qa.ask(f"What is {concept}?")
        if "don't know" in truth.lower():
            return f"Information about {concept} is not available."
        
        if concept_lower in self.signal_frames:
            return self.signal_frames[concept_lower]
        
        # Encode truth
        truth_q = self._encode_sentence(truth)
        
        # Find nearest signals
        nearest = self._find_nearest(truth_q, k=5)
        
        # Compute target quaternion (average of nearest signals)
        if nearest:
            target_q = Quaternion(
                sum(q.w for q, _, _ in nearest) / len(nearest),
                sum(q.x for q, _, _ in nearest) / len(nearest),
                sum(q.y for q, _, _ in nearest) / len(nearest),
                sum(q.z for q, _, _ in nearest) / len(nearest),
            ).normalize()
        else:
            target_q = truth_q
        
        # SLERP blend between truth and target
        blended_q = truth_q.slerp(target_q, blend_ratio)
        
        # Use blended quaternion to make style decisions
        return self._generate_from_quaternion(truth, concept, blended_q)
    
    def _find_nearest(self, target_q: Quaternion, k: int = 5) -> List[Tuple[Quaternion, str, str]]:
        """Find k nearest signals by quaternion similarity."""
        scored = []
        for q, text, agent in self.signal_index:
            sim = abs(target_q.dot(q))
            scored.append((sim, q, text, agent))
        
        scored.sort(key=lambda x: -x[0])
        return [(q, text, agent) for _, q, text, agent in scored[:k]]
    
    def _generate_from_quaternion(self, truth: str, concept: str, q: Quaternion) -> str:
        """
        Generate output using quaternion to guide style choices.
        
        The quaternion components influence:
        - w: formality (high = formal "is a", low = informal "seems to be")
        - x: position emphasis (affects word order)
        - y: verb style (high = gerunds, low = base forms)
        - z: connector choice (high = relative pronouns, low = "that involves")
        """
        # Parse truth
        entity, role, actions, targets = self._parse_truth(truth, concept)
        
        # Normalize quaternion
        q = q.normalize()
        
        # STYLE DECISIONS BASED ON QUATERNION:
        
        # 1. Formality (w component)
        if q.w > 0.3:
            prefix = f"{entity} is"
        elif q.w > 0:
            prefix = f"{entity} seems to be"
        else:
            prefix = f"It appears that {entity} is"
        
        # 2. Article
        article = "an" if role[0].lower() in 'aeiou' else "a"
        
        # 3. Verb style (y component)
        if q.y > 0.2:
            # High y = prefer gerunds
            transformed_actions = [self._to_gerund(a) for a in actions]
        else:
            # Low y = keep base forms
            transformed_actions = actions
        
        # 4. Connector (z component)
        if q.z > 0.3:
            connector = "who"
            # With "who", we might want non-gerund forms
            if q.y <= 0.2:
                transformed_actions = actions  # Keep base forms with "who"
        elif q.z > 0:
            connector = "that"
        else:
            connector = "that involves"
        
        # Build action string
        if transformed_actions:
            if len(transformed_actions) == 1:
                action_str = transformed_actions[0]
            elif len(transformed_actions) == 2:
                action_str = f"{transformed_actions[0]} and {transformed_actions[1]}"
            else:
                action_str = f"{transformed_actions[0]}, {transformed_actions[1]}, and {transformed_actions[2]}"
        else:
            action_str = ""
        
        # Build target string
        target_str = ' and '.join(targets[:2]) if targets else ""
        
        # 5. Target connector (based on x component - position)
        if q.x > 0:
            target_connector = "particularly"
        else:
            target_connector = "relating to"
        
        # Construct output
        if action_str and target_str:
            if connector == "that involves":
                return f"{prefix} {article} {role} {connector} {action_str}, {target_connector} {target_str}."
            else:
                return f"{prefix} {article} {role} {connector} {action_str}, {target_connector} {target_str}."
        elif action_str:
            if connector == "that involves":
                return f"{prefix} {article} {role} {connector} {action_str}."
            else:
                return f"{prefix} {article} {role} {connector} {action_str}."
        elif target_str:
            return f"{prefix} {article} {role} {target_connector} {target_str}."
        else:
            return f"{prefix} {article} {role}."
    
    def _parse_truth(self, truth: str, concept: str) -> Tuple[str, str, List[str], List[str]]:
        """Parse truth into components."""
        truth_lower = truth.lower()
        
        entity = concept.title()
        role = "entity"
        actions = []
        targets = []
        
        match = re.search(r'is a[n]? (\w+)', truth_lower)
        if match:
            role = match.group(1)
        
        match = re.search(r'who\s+(\w+)(?:,\s*(\w+))?(?:,?\s*and\s*(\w+))?', truth_lower)
        if match:
            actions = [a for a in match.groups() if a]
        else:
            match = re.search(r'is a \w+ that\s+(\w+)(?:,\s*(\w+))?(?:,?\s*and\s*(\w+))?', truth_lower)
            if match:
                actions = [a for a in match.groups() if a]
        
        match = re.search(r'(?:relates to|involving)\s+(\w+)(?:\s+and\s+(\w+))?', truth_lower)
        if match:
            targets = [t for t in match.groups() if t]
        
        return entity, role, actions, targets
    
    def _to_gerund(self, verb: str) -> str:
        """Convert verb to gerund."""
        verb = verb.lower()
        if verb.endswith('ing'):
            return verb
        elif verb.endswith('e') and not verb.endswith('ee'):
            return verb[:-1] + 'ing'
        elif verb.endswith('s') and not verb.endswith('ss'):
            base = verb[:-1]
            if base.endswith('e') and not base.endswith('ee'):
                return base[:-1] + 'ing'
            return base + 'ing'
        else:
            return verb + 'ing'


def demo():
    """Demo the gear blend projector."""
    print("=" * 70)
    print("GEAR BLEND PROJECTION")
    print("Quaternion SLERP blending for style control")
    print("=" * 70)
    
    truth_path = "truthspace_lcm/corpus_experimental.json"
    signal_path = "truthspace_lcm/corpus_signal_full.json"
    
    projector = GearBlendProjector(truth_path, signal_path)
    
    # Show style quaternions
    print("\nStyle quaternions:")
    for style, q in projector.style_quaternions.items():
        print(f"  {style}: w={q.w:.3f}, x={q.x:.3f}, y={q.y:.3f}, z={q.z:.3f}")
    
    # Find test concepts
    test_concepts = []
    for concept in projector.truth_qa.knowledge.concepts:
        if concept not in projector.signal_frames:
            c = projector.truth_qa.knowledge.concepts[concept]
            if c.is_content_word and c.actions and len(c.actions) >= 2:
                test_concepts.append(concept)
        if len(test_concepts) >= 6:
            break
    
    print("\n" + "=" * 70)
    print("Testing with different blend ratios:")
    print("=" * 70)
    
    for concept in test_concepts[:3]:
        truth = projector.truth_qa.ask(f"What is {concept}?")
        print(f"\n{concept.upper()}")
        print(f"  TRUTH: {truth}")
        
        for ratio in [0.0, 0.5, 1.0]:
            result = projector.project(concept, blend_ratio=ratio)
            print(f"  BLEND {ratio:.1f}: {result}")


if __name__ == "__main__":
    demo()
