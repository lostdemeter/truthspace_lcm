class FeatureExtractor:
    """
    Extract features from RGB and depth images for geometric learning.
    
    Features are designed to capture properties that correlate with depth:
    - Brightness gradients (sky is bright, ground is dark)
    - Color statistics (blue sky, green ground)
    - Texture patterns (smooth sky, textured ground)
    - Edge density (more edges = closer objects typically)
    """
    
    @staticmethod
    def extract_rgb_features(image: np.ndarray) -> Dict[str, float]:
        """Extract features from an RGB image."""
        if len(image.shape) != 3:
            image = np.stack([image] * 3, axis=-1)
        
        # Normalize
        if image.max() > 1.0:
            image = image / 255.0
        
        h, w = image.shape[:2]
        features = {}
        
        # Global statistics
        features['mean_brightness'] = np.mean(image)
        features['std_brightness'] = np.std(image)
        
        # Per-channel means
        features['mean_red'] = np.mean(image[:, :, 0])
        features['mean_green'] = np.mean(image[:, :, 1])
        features['mean_blue'] = np.mean(image[:, :, 2])
        
        # Vertical gradient (sky vs ground)
        top_half = image[:h//2, :, :]
        bottom_half = image[h//2:, :, :]
        features['vertical_gradient'] = np.mean(top_half) - np.mean(bottom_half)
        
        # Horizontal symmetry (handle odd widths)
        min_w = min(w//2, w - w//2)
        left_half = image[:, :min_w, :]
        right_half = image[:, w-min_w:, :]
        features['horizontal_symmetry'] = 1.0 - np.mean(np.abs(left_half - np.flip(right_half, axis=1)))
        
        # Edge density (proxy for texture/detail)
        gray = np.mean(image, axis=2)
        edges_h = np.abs(gray[1:, :] - gray[:-1, :])
        edges_v = np.abs(gray[:, 1:] - gray[:, :-1])
        features['edge_density'] = (np.mean(edges_h) + np.mean(edges_v)) / 2
        
        # Color variance
        features['color_variance'] = np.var(image)
        
        # Blue sky indicator (high blue in top region)
        features['sky_blueness'] = np.mean(top_half[:, :, 2]) - np.mean(top_half[:, :, :2])
        
        # Center vs periphery (objects often in center)
        center_region = image[h//4:3*h//4, w//4:3*w//4, :]
        features['center_brightness'] = np.mean(center_region)
        
        return features
    
    @staticmethod
    def extract_depth_features(depth: np.ndarray) -> Dict[str, float]:
        """Extract features from a depth map."""
        if depth.max() > 1.0:
            depth = depth / depth.max()
        
        h, w = depth.shape[:2]
        if len(depth.shape) == 3:
            depth = np.mean(depth, axis=2)
        
        features = {}
        
        # Global statistics
        features['mean_depth'] = np.mean(depth)
        features['std_depth'] = np.std(depth)
        features['min_depth'] = np.min(depth)
        features['max_depth'] = np.max(depth)
        features['depth_range'] = np.max(depth) - np.min(depth)
        
        # Vertical gradient (typically sky=far, ground=near)
        top_half = depth[:h//2, :]
        bottom_half = depth[h//2:, :]
        features['vertical_depth_gradient'] = np.mean(bottom_half) - np.mean(top_half)
        
        # Center depth (objects in center)
        center_region = depth[h//4:3*h//4, w//4:3*w//4]
        features['center_depth'] = np.mean(center_region)
        
        # Depth complexity (variance in local regions)
        features['depth_complexity'] = np.var(depth)
        
        # Edge sharpness in depth
        edges_h = np.abs(depth[1:, :] - depth[:-1, :])
        edges_v = np.abs(depth[:, 1:] - depth[:, :-1])
        features['depth_edge_sharpness'] = (np.mean(edges_h) + np.mean(edges_v)) / 2
        
        return features
    
    @staticmethod
    def features_to_vector(features: Dict[str, float], feature_names: List[str] = None) -> np.ndarray:
        """Convert feature dict to numpy vector."""
        if feature_names is None:
            feature_names = sorted(features.keys())
        return np.array([features.get(name, 0.0) for name in feature_names])


