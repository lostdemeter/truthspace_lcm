class DepthEstimator:
    """
    Wrapper for Depth Anything V2 via Hugging Face Transformers.
    """
    
    def __init__(self, model_name: str = "depth-anything/Depth-Anything-V2-Small-hf"):
        self.model_name = model_name
        self.pipe = None
        
        if TRANSFORMERS_AVAILABLE and TORCH_AVAILABLE:
            try:
                print(f"Loading depth model: {model_name}")
                self.pipe = pipeline(task="depth-estimation", model=model_name)
                print("Depth model loaded successfully!")
            except Exception as e:
                print(f"Failed to load depth model: {e}")
                self.pipe = None
    
    def estimate(self, image_path: Path) -> Optional[np.ndarray]:
        """Estimate depth for an image."""
        if self.pipe is None:
            return self._mock_depth(image_path)
        
        try:
            image = Image.open(image_path).convert("RGB")
            result = self.pipe(image)
            depth = np.array(result["depth"])
            
            # Normalize to 0-1
            depth = depth.astype(np.float32)
            if depth.max() > depth.min():
                depth = (depth - depth.min()) / (depth.max() - depth.min())
            
            return depth
        except Exception as e:
            print(f"Error estimating depth for {image_path}: {e}")
            return None
    
    def _mock_depth(self, image_path: Path) -> np.ndarray:
        """Generate mock depth for testing without the model."""
        image = Image.open(image_path).convert("RGB")
        img_array = np.array(image).astype(np.float32) / 255.0
        
        # Simple mock: use luminance as depth proxy
        if len(img_array.shape) == 3:
            depth = 0.299 * img_array[:, :, 0] + 0.587 * img_array[:, :, 1] + 0.114 * img_array[:, :, 2]
        else:
            depth = img_array
        
        return depth


