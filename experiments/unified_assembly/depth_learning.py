def run_depth_learning_experiment(n_train: int = 50, n_test: int = 10):
    """
    Run the depth learning experiment.
    
    1. Load COCO images
    2. Generate depth maps with Depth Anything V2
    3. Extract features from RGB and depth
    4. Train geometric learner
    5. Evaluate on held-out test set
    """
    print("=" * 70)
    print("EXPERIMENT: Learning Depth Estimation Geometrically")
    print("=" * 70)
    print()
    print("Hypothesis: Can φ-geometry LEARN depth estimation from examples?")
    print()
    
    # Check for images
    if not COCO_VAL_PATH.exists():
        print(f"Error: COCO val2017 not found at {COCO_VAL_PATH}")
        return None
    
    image_files = sorted(COCO_VAL_PATH.glob("*.jpg"))[:n_train + n_test]
    print(f"Found {len(image_files)} images")
    
    if len(image_files) < n_train + n_test:
        print(f"Warning: Only {len(image_files)} images available")
        n_train = min(n_train, len(image_files) - n_test)
    
    # Initialize components
    depth_estimator = DepthEstimator()
    learner = GeometricDepthLearner()
    
    # Create depth cache directory
    DEPTH_CACHE_PATH.mkdir(exist_ok=True)
    
    # Training phase
    print()
    print("=" * 60)
    print("PHASE 1: Generating Training Data")
    print("=" * 60)
    
    train_files = image_files[:n_train]
    
    for i, img_path in enumerate(train_files):
        print(f"\r  Processing {i+1}/{n_train}: {img_path.name}", end="")
        
        # Load RGB image
        rgb_image = np.array(Image.open(img_path).convert("RGB")).astype(np.float32) / 255.0
        
        # Get or generate depth
        depth_cache_file = DEPTH_CACHE_PATH / f"{img_path.stem}_depth.npy"
        if depth_cache_file.exists():
            depth = np.load(depth_cache_file)
        else:
            depth = depth_estimator.estimate(img_path)
            if depth is not None:
                np.save(depth_cache_file, depth)
        
        if depth is None:
            continue
        
        # Resize depth to match RGB if needed
        if depth.shape[:2] != rgb_image.shape[:2]:
            from PIL import Image as PILImage
            depth_pil = PILImage.fromarray((depth * 255).astype(np.uint8))
            depth_pil = depth_pil.resize((rgb_image.shape[1], rgb_image.shape[0]))
            depth = np.array(depth_pil).astype(np.float32) / 255.0
        
        # Extract features
        rgb_features = FeatureExtractor.extract_rgb_features(rgb_image)
        depth_features = FeatureExtractor.extract_depth_features(depth)
        
        # Add to learner
        learner.add_sample(rgb_features, depth_features)
    
    print()
    print(f"  Collected {learner.n_samples} training samples")
    
    # Learning phase
    print()
    print("=" * 60)
    print("PHASE 2: Learning Geometric Transformation")
    print("=" * 60)
    
    success = learner.learn()
    if not success:
        print("  Learning failed!")
        return None
    
    print(f"  Learned W matrix: {learner.W.shape}")
    print(f"  RGB features: {len(learner.rgb_feature_names)}")
    print(f"  Depth features: {len(learner.depth_feature_names)}")
    
    # Evaluation phase
    print()
    print("=" * 60)
    print("PHASE 3: Evaluating on Test Set")
    print("=" * 60)
    
    test_files = image_files[n_train:n_train + n_test]
    test_errors = []
    
    for i, img_path in enumerate(test_files):
        print(f"\r  Testing {i+1}/{len(test_files)}: {img_path.name}", end="")
        
        # Load RGB image
        rgb_image = np.array(Image.open(img_path).convert("RGB")).astype(np.float32) / 255.0
        
        # Get depth
        depth_cache_file = DEPTH_CACHE_PATH / f"{img_path.stem}_depth.npy"
        if depth_cache_file.exists():
            depth = np.load(depth_cache_file)
        else:
            depth = depth_estimator.estimate(img_path)
            if depth is not None:
                np.save(depth_cache_file, depth)
        
        if depth is None:
            continue
        
        # Resize if needed
        if depth.shape[:2] != rgb_image.shape[:2]:
            from PIL import Image as PILImage
            depth_pil = PILImage.fromarray((depth * 255).astype(np.uint8))
            depth_pil = depth_pil.resize((rgb_image.shape[1], rgb_image.shape[0]))
            depth = np.array(depth_pil).astype(np.float32) / 255.0
        
        # Extract features
        rgb_features = FeatureExtractor.extract_rgb_features(rgb_image)
        true_depth_features = FeatureExtractor.extract_depth_features(depth)
        
        # Evaluate
        eval_result = learner.evaluate(rgb_features, true_depth_features)
        test_errors.append(eval_result['mae'])
    
    print()
    
    # Results
    print()
    print("=" * 60)
    print("RESULTS")
    print("=" * 60)
    
    mean_mae = np.mean(test_errors)
    std_mae = np.std(test_errors)
    
    print(f"  Test samples: {len(test_errors)}")
    print(f"  Mean Absolute Error: {mean_mae:.4f}")
    print(f"  Std Absolute Error: {std_mae:.4f}")
    print()
    
    # Show feature correlations
    print("Feature prediction quality:")
    
    # Get one sample for detailed analysis
    if test_files:
        img_path = test_files[0]
        rgb_image = np.array(Image.open(img_path).convert("RGB")).astype(np.float32) / 255.0
        
        depth_cache_file = DEPTH_CACHE_PATH / f"{img_path.stem}_depth.npy"
        if depth_cache_file.exists():
            depth = np.load(depth_cache_file)
            if depth.shape[:2] != rgb_image.shape[:2]:
                from PIL import Image as PILImage
                depth_pil = PILImage.fromarray((depth * 255).astype(np.uint8))
                depth_pil = depth_pil.resize((rgb_image.shape[1], rgb_image.shape[0]))
                depth = np.array(depth_pil).astype(np.float32) / 255.0
            
            rgb_features = FeatureExtractor.extract_rgb_features(rgb_image)
            true_depth = FeatureExtractor.extract_depth_features(depth)
            predicted_depth = learner.predict(rgb_features)
            
            print(f"\n  Sample: {img_path.name}")
            print(f"  {'Feature':<25} {'True':>10} {'Predicted':>10} {'Error':>10}")
            print(f"  {'-'*55}")
            
            for name in learner.depth_feature_names:
                true_val = true_depth.get(name, 0)
                pred_val = predicted_depth.get(name, 0)
                error = abs(true_val - pred_val)
                print(f"  {name:<25} {true_val:>10.4f} {pred_val:>10.4f} {error:>10.4f}")
    
    # Conclusion
    print()
    print("=" * 60)
    print("CONCLUSION")
    print("=" * 60)
    print()
    
    if mean_mae < 0.2:
        print("✓ SUCCESS: Geometric learning achieved reasonable accuracy!")
        print("  The φ-geometry CAN learn complex transformations.")
    elif mean_mae < 0.4:
        print("◐ PARTIAL: Some learning occurred, but accuracy is limited.")
        print("  More features or samples might improve results.")
    else:
        print("✗ LIMITED: Learning was not very successful.")
        print("  This transformation may require different features or approach.")
    
    print()
    print("Key insight:")
    print("  We used the probe extraction formula: W = Y @ X @ (X^T X)^(-1)")
    print("  This is EXACT geometric learning, not gradient descent.")
    print("  The same formula works for text (king→queen) and images (RGB→depth).")
    print()
    
    return learner


