# GEOMETRIC DEPTH LEARNER
# =============================================================================

class GeometricDepthLearner:
    """
    Learn depth estimation using φ-geometry.
    
    The approach:
    1. Extract features from RGB and depth images
    2. Build a mapping matrix W such that: depth_features ≈ W @ rgb_features
    3. This is learned geometrically, not via gradient descent
    
    Key insight: This is the probe extraction formula from the project:
    W = Y @ X @ (X^T X)^(-1)
    
    Where:
    - X = matrix of RGB feature vectors
    - Y = matrix of depth feature vectors
    - W = learned transformation matrix
    """
    
    def __init__(self):
        self.rgb_feature_names: List[str] = []
        self.depth_feature_names: List[str] = []
        
        # Training data
        self.rgb_features: List[np.ndarray] = []
        self.depth_features: List[np.ndarray] = []
        
        # Learned transformation
        self.W: Optional[np.ndarray] = None
        
        # Statistics
        self.n_samples = 0
    
    def add_sample(self, rgb_features: Dict[str, float], depth_features: Dict[str, float]):
        """Add a training sample."""
        # Initialize feature names on first sample
        if not self.rgb_feature_names:
            self.rgb_feature_names = sorted(rgb_features.keys())
            self.depth_feature_names = sorted(depth_features.keys())
        
        # Convert to vectors
        rgb_vec = FeatureExtractor.features_to_vector(rgb_features, self.rgb_feature_names)
        depth_vec = FeatureExtractor.features_to_vector(depth_features, self.depth_feature_names)
        
        self.rgb_features.append(rgb_vec)
        self.depth_features.append(depth_vec)
        self.n_samples += 1
    
    def learn(self) -> bool:
        """
        Learn the geometric transformation W.
        
        Uses the probe extraction formula:
        W = Y @ X @ (X^T X)^(-1)
        """
        if self.n_samples < 2:
            print("Need at least 2 samples to learn")
            return False
        
        # Build matrices
        X = np.array(self.rgb_features).T  # (n_rgb_features, n_samples)
        Y = np.array(self.depth_features).T  # (n_depth_features, n_samples)
        
        # Normalize features
        X_mean = X.mean(axis=1, keepdims=True)
        X_std = X.std(axis=1, keepdims=True) + 1e-8
        X_norm = (X - X_mean) / X_std
        
        Y_mean = Y.mean(axis=1, keepdims=True)
        Y_std = Y.std(axis=1, keepdims=True) + 1e-8
        Y_norm = (Y - Y_mean) / Y_std
        
        # Store normalization parameters
        self.X_mean = X_mean
        self.X_std = X_std
        self.Y_mean = Y_mean
        self.Y_std = Y_std
        
        # Compute W = Y @ X^T @ (X @ X^T)^(-1)
        try:
            XXT = X_norm @ X_norm.T
            XXT_inv = np.linalg.pinv(XXT)  # Use pseudo-inverse for stability
            self.W = Y_norm @ X_norm.T @ XXT_inv
            
            print(f"Learned transformation matrix W: {self.W.shape}")
            return True
        except Exception as e:
            print(f"Failed to learn: {e}")
            return False
    
    def predict(self, rgb_features: Dict[str, float]) -> Dict[str, float]:
        """Predict depth features from RGB features."""
        if self.W is None:
            raise ValueError("Model not trained yet")
        
        # Convert to vector
        rgb_vec = FeatureExtractor.features_to_vector(rgb_features, self.rgb_feature_names)
        
        # Normalize
        rgb_norm = (rgb_vec.reshape(-1, 1) - self.X_mean) / self.X_std
        
        # Predict
        depth_norm = self.W @ rgb_norm
        
        # Denormalize
        depth_vec = depth_norm * self.Y_std + self.Y_mean
        
        # Convert back to dict
        return {name: float(depth_vec[i, 0]) 
                for i, name in enumerate(self.depth_feature_names)}
    
    def evaluate(self, rgb_features: Dict[str, float], 
                 true_depth_features: Dict[str, float]) -> Dict[str, float]:
        """Evaluate prediction accuracy."""
        predicted = self.predict(rgb_features)
        
        errors = {}
        for name in self.depth_feature_names:
            true_val = true_depth_features.get(name, 0)
            pred_val = predicted.get(name, 0)
            errors[name] = abs(true_val - pred_val)
        
        return {
            'mae': np.mean(list(errors.values())),
            'max_error': max(errors.values()),
            'per_feature': errors
        }


