#!/usr/bin/env python3
"""
Gear Chain Chatbot

A chatbot that uses ONLY the emergent gear chain for understanding and response.
NO LLM is used for response generation - only for initial corpus training.

The response is generated by:
1. Analyzing the query dimensionally
2. Finding relevant frames from the knowledge base
3. Composing a response from retrieved information
"""

import json
import numpy as np
import re
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Tuple, Optional, Any
from dataclasses import dataclass, field


@dataclass
class KnowledgeFrame:
    """A piece of knowledge with dimensional position."""
    text: str
    agent: str
    source: str
    position: Optional[np.ndarray] = None
    metadata: Dict[str, Any] = field(default_factory=dict)


class GearChainChatbot:
    """
    A chatbot powered entirely by the emergent gear chain.
    
    NO LLM is used for response generation. Responses are composed
    from retrieved knowledge frames based on dimensional similarity.
    """
    
    def __init__(self):
        # Knowledge base
        self.frames: List[KnowledgeFrame] = []
        self.agent_actions: Dict[str, Dict[str, int]] = defaultdict(lambda: defaultdict(int))
        
        # Discovered dimensions
        self.dimensions: List[Dict] = []
        self.agents: List[str] = []
        self.features: List[str] = []
        
        # SVD components
        self.U: Optional[np.ndarray] = None
        self.S: Optional[np.ndarray] = None
        self.Vt: Optional[np.ndarray] = None
        
        # Response templates
        self.templates = {
            'describe': "Based on the knowledge base: {content}",
            'compare': "{agent1} and {agent2} differ primarily in {dimension}. {agent1} is more toward {pole1}, while {agent2} is toward {pole2}. {details}",
            'similar': "{agent} is similar to: {similar_list}. {details}",
            'opposite': "{agent} is opposite to {opposite}. {details}",
            'unknown': "I don't have specific information about '{query}' in my knowledge base. Known concepts include: {known}",
        }
        
        self.total_frames = 0
        self.learning_cycles = 0
    
    def ingest_corpus(self, corpus_path: str, source_name: str = None):
        """Ingest a corpus file."""
        with open(corpus_path) as f:
            corpus = json.load(f)
        
        frames = corpus.get('frames', [])
        source = source_name or Path(corpus_path).stem
        
        for frame in frames:
            text = frame.get('text', '')
            agent = frame.get('agent', '').lower()
            
            if not text or len(text) < 10:
                continue
            
            kf = KnowledgeFrame(
                text=text,
                agent=agent if agent else 'unknown',
                source=source,
                metadata=frame.get('metadata', {}),
            )
            self.frames.append(kf)
            self._extract_patterns(text, agent)
        
        self.total_frames = len(self.frames)
        print(f"Ingested {len(frames)} frames from {source}, total: {self.total_frames}")
    
    def _extract_patterns(self, text: str, agent: str):
        """Extract behavioral patterns from text."""
        if not agent or len(agent) < 2:
            return
        
        words = text.lower().split()
        for word in words:
            word_clean = re.sub(r'[^a-z]', '', word)
            if len(word_clean) < 3:
                continue
            
            verb_endings = ['ed', 'ing', 'es', 's', 'ly']
            if any(word_clean.endswith(e) for e in verb_endings):
                self.agent_actions[agent][word_clean] += 1
    
    def learn_dimensions(self, min_variance: float = 0.02, max_dims: int = 15):
        """Learn dimensions from accumulated data."""
        self.learning_cycles += 1
        
        min_actions = 3
        valid_agents = {
            a: v for a, v in self.agent_actions.items()
            if sum(v.values()) >= min_actions and len(a) > 2
        }
        
        if len(valid_agents) < 3:
            print("Not enough agents for dimension learning")
            return
        
        self.agents = list(valid_agents.keys())
        
        all_actions = set()
        for actions in valid_agents.values():
            all_actions.update(actions.keys())
        self.features = sorted(all_actions)
        
        n_agents = len(self.agents)
        n_features = len(self.features)
        
        print(f"Learning dimensions: {n_agents} agents × {n_features} features")
        
        X = np.zeros((n_agents, n_features))
        for i, agent in enumerate(self.agents):
            actions = valid_agents[agent]
            total = sum(actions.values())
            if total > 0:
                for j, action in enumerate(self.features):
                    X[i, j] = actions.get(action, 0) / total
        
        X_centered = X - X.mean(axis=0)
        self.U, self.S, self.Vt = np.linalg.svd(X_centered, full_matrices=False)
        
        total_var = np.sum(self.S ** 2)
        var_ratios = (self.S ** 2) / total_var
        
        self.dimensions = []
        cumulative = 0.0
        
        for i in range(min(len(self.S), max_dims)):
            var = var_ratios[i]
            cumulative += var
            
            if var < min_variance:
                break
            
            positions = self.U[:, i]
            min_idx = np.argmin(positions)
            max_idx = np.argmax(positions)
            
            feature_weights = self.Vt[i]
            neg_features = [self.features[j] for j in np.argsort(feature_weights)[:3]]
            pos_features = [self.features[j] for j in np.argsort(feature_weights)[-3:]]
            
            dim = {
                'index': i,
                'name': f'Dim{i+1}',
                'variance': float(var),
                'negative_pole': self.agents[min_idx],
                'positive_pole': self.agents[max_idx],
                'negative_features': neg_features,
                'positive_features': pos_features,
                'positions': {self.agents[j]: float(positions[j]) for j in range(n_agents)},
            }
            self.dimensions.append(dim)
        
        print(f"Discovered {len(self.dimensions)} dimensions ({cumulative*100:.1f}% variance)")
        self._update_frame_positions()
    
    def _update_frame_positions(self):
        """Update dimensional positions for all frames."""
        for frame in self.frames:
            if frame.agent in self.agents:
                pos = np.array([
                    dim['positions'].get(frame.agent, 0) 
                    for dim in self.dimensions
                ])
                frame.position = pos
    
    def _get_position(self, concept: str) -> Optional[np.ndarray]:
        """Get dimensional position of a concept."""
        concept_lower = concept.lower()
        
        if concept_lower in self.agents:
            return np.array([
                dim['positions'].get(concept_lower, 0)
                for dim in self.dimensions
            ])
        
        for agent in self.agents:
            if concept_lower in agent or agent in concept_lower:
                return np.array([
                    dim['positions'].get(agent, 0)
                    for dim in self.dimensions
                ])
        
        return None
    
    def _find_agent(self, concept: str) -> Optional[str]:
        """Find the agent name for a concept."""
        concept_lower = concept.lower()
        
        if concept_lower in self.agents:
            return concept_lower
        
        for agent in self.agents:
            if concept_lower in agent or agent in concept_lower:
                return agent
        
        return None
    
    def _extract_concepts(self, query: str) -> List[str]:
        """Extract concepts from query."""
        query_lower = query.lower()
        found = []
        
        for agent in self.agents:
            if agent in query_lower and len(agent) > 2:
                found.append(agent)
        
        return found
    
    def _find_similar(self, agent: str, k: int = 5) -> List[Tuple[str, float]]:
        """Find similar agents."""
        pos = self._get_position(agent)
        if pos is None:
            return []
        
        similarities = []
        for other in self.agents:
            if other != agent:
                other_pos = self._get_position(other)
                if other_pos is not None:
                    dist = np.linalg.norm(pos - other_pos)
                    similarities.append((other, dist))
        
        return sorted(similarities, key=lambda x: x[1])[:k]
    
    def _find_opposite(self, agent: str) -> Optional[str]:
        """Find the most opposite agent."""
        pos = self._get_position(agent)
        if pos is None:
            return None
        
        max_dist = 0
        opposite = None
        
        for other in self.agents:
            if other != agent:
                other_pos = self._get_position(other)
                if other_pos is not None:
                    dist = np.linalg.norm(pos - other_pos)
                    if dist > max_dist:
                        max_dist = dist
                        opposite = other
        
        return opposite
    
    def _find_relevant_frames(self, concepts: List[str], k: int = 5) -> List[KnowledgeFrame]:
        """Find frames relevant to concepts."""
        if not concepts:
            return []
        
        positions = []
        for concept in concepts:
            pos = self._get_position(concept)
            if pos is not None:
                positions.append(pos)
        
        if not positions:
            relevant = []
            for frame in self.frames:
                score = sum(1 for c in concepts if c in frame.text.lower() or c in frame.agent)
                if score > 0:
                    relevant.append((score, frame))
            relevant.sort(key=lambda x: -x[0])
            return [f for _, f in relevant[:k]]
        
        query_pos = np.mean(positions, axis=0)
        
        scored = []
        for frame in self.frames:
            if frame.position is not None:
                dist = np.linalg.norm(frame.position - query_pos)
                text_match = sum(1 for c in concepts if c in frame.text.lower())
                score = -dist + text_match * 0.5
                scored.append((score, frame))
        
        scored.sort(key=lambda x: -x[0])
        return [f for _, f in scored[:k]]
    
    def _get_dimensional_description(self, agent: str) -> str:
        """Get a description of an agent's dimensional position."""
        pos = self._get_position(agent)
        if pos is None:
            return ""
        
        descriptions = []
        for i, dim in enumerate(self.dimensions):
            if i < len(pos):
                p = pos[i]
                if p > 0.15:
                    descriptions.append(f"toward {dim['positive_pole']}")
                elif p < -0.15:
                    descriptions.append(f"toward {dim['negative_pole']}")
        
        if descriptions:
            return f"Dimensionally, {agent} is {', '.join(descriptions[:3])}"
        return ""
    
    def _detect_query_type(self, query: str) -> str:
        """Detect the type of query."""
        query_lower = query.lower()
        
        if any(w in query_lower for w in ['compare', 'difference', 'between', 'vs', 'versus']):
            return 'compare'
        if any(w in query_lower for w in ['similar', 'like', 'related']):
            return 'similar'
        if any(w in query_lower for w in ['opposite', 'contrary', 'antithesis']):
            return 'opposite'
        
        return 'describe'
    
    def chat(self, query: str) -> str:
        """
        Process a query and generate a response using ONLY the gear chain.
        NO LLM is used here.
        """
        concepts = self._extract_concepts(query)
        query_type = self._detect_query_type(query)
        
        # Handle unknown concepts
        if not concepts:
            known_sample = ', '.join(self.agents[:10])
            return self.templates['unknown'].format(
                query=query,
                known=known_sample + "..."
            )
        
        # Get relevant frames
        relevant_frames = self._find_relevant_frames(concepts, k=5)
        
        # Build response based on query type
        if query_type == 'compare' and len(concepts) >= 2:
            return self._generate_compare_response(concepts[0], concepts[1], relevant_frames)
        elif query_type == 'similar' and concepts:
            return self._generate_similar_response(concepts[0], relevant_frames)
        elif query_type == 'opposite' and concepts:
            return self._generate_opposite_response(concepts[0], relevant_frames)
        else:
            return self._generate_describe_response(concepts, relevant_frames)
    
    def _generate_describe_response(self, concepts: List[str], frames: List[KnowledgeFrame]) -> str:
        """Generate a description response."""
        parts = []
        
        for concept in concepts:
            agent = self._find_agent(concept)
            if not agent:
                continue
            
            # Dimensional description
            dim_desc = self._get_dimensional_description(agent)
            if dim_desc:
                parts.append(dim_desc + ".")
            
            # Similar concepts
            similar = self._find_similar(agent, k=3)
            if similar:
                similar_names = [s[0] for s in similar]
                parts.append(f"{agent.title()} is similar to: {', '.join(similar_names)}.")
            
            # Opposite
            opposite = self._find_opposite(agent)
            if opposite:
                parts.append(f"Opposite of {agent}: {opposite}.")
        
        # Add relevant frame content
        if frames:
            parts.append("\nRelevant information:")
            for frame in frames[:3]:
                parts.append(f"  • {frame.text[:200]}")
        
        if not parts:
            return f"I found {concepts} but have limited information about them."
        
        return "\n".join(parts)
    
    def _generate_compare_response(self, agent1: str, agent2: str, frames: List[KnowledgeFrame]) -> str:
        """Generate a comparison response."""
        pos1 = self._get_position(agent1)
        pos2 = self._get_position(agent2)
        
        if pos1 is None or pos2 is None:
            return f"Cannot compare: missing dimensional data for {agent1 if pos1 is None else agent2}"
        
        # Find most different dimension
        diff = pos2 - pos1
        max_diff_idx = np.argmax(np.abs(diff))
        max_dim = self.dimensions[max_diff_idx]
        
        if diff[max_diff_idx] > 0:
            pole1, pole2 = max_dim['negative_pole'], max_dim['positive_pole']
        else:
            pole1, pole2 = max_dim['positive_pole'], max_dim['negative_pole']
        
        # Distance
        distance = np.linalg.norm(diff)
        similarity = "very similar" if distance < 0.5 else "somewhat similar" if distance < 1.0 else "quite different"
        
        # Build response
        parts = [
            f"{agent1.title()} and {agent2.title()} are {similarity} (distance: {distance:.2f}).",
            f"They differ most on {max_dim['name']}: {agent1} is toward {pole1}, {agent2} is toward {pole2}.",
        ]
        
        # Add frame details
        if frames:
            parts.append("\nRelevant details:")
            for frame in frames[:2]:
                parts.append(f"  • {frame.text[:150]}")
        
        return "\n".join(parts)
    
    def _generate_similar_response(self, agent: str, frames: List[KnowledgeFrame]) -> str:
        """Generate a similarity response."""
        similar = self._find_similar(agent, k=5)
        
        if not similar:
            return f"No similar concepts found for {agent}"
        
        parts = [
            f"Concepts similar to {agent.title()}:",
        ]
        
        for name, dist in similar:
            parts.append(f"  • {name} (distance: {dist:.2f})")
        
        if frames:
            parts.append("\nRelevant information:")
            for frame in frames[:2]:
                parts.append(f"  • {frame.text[:150]}")
        
        return "\n".join(parts)
    
    def _generate_opposite_response(self, agent: str, frames: List[KnowledgeFrame]) -> str:
        """Generate an opposite response."""
        opposite = self._find_opposite(agent)
        
        if not opposite:
            return f"No opposite found for {agent}"
        
        pos1 = self._get_position(agent)
        pos2 = self._get_position(opposite)
        distance = np.linalg.norm(pos2 - pos1) if pos1 is not None and pos2 is not None else 0
        
        parts = [
            f"The opposite of {agent.title()} is {opposite.title()} (distance: {distance:.2f}).",
        ]
        
        # Show dimensional differences
        if pos1 is not None and pos2 is not None:
            diff = pos2 - pos1
            for i, dim in enumerate(self.dimensions[:3]):
                if i < len(diff):
                    parts.append(f"  • {dim['name']}: {agent} vs {opposite} (Δ={diff[i]:+.2f})")
        
        return "\n".join(parts)
    
    def interactive_chat(self):
        """Run interactive chat session."""
        print("\n" + "═" * 70)
        print(" GEAR CHAIN CHATBOT (No LLM) ".center(70, "═"))
        print("═" * 70)
        print(f"\nKnowledge: {self.total_frames} frames, {len(self.agents)} agents")
        print(f"Dimensions: {len(self.dimensions)}")
        print("\nCommands: 'dims', 'agents', 'quit'")
        print()
        
        while True:
            try:
                query = input("You: ").strip()
            except (EOFError, KeyboardInterrupt):
                print("\nGoodbye!")
                break
            
            if not query:
                continue
            
            if query.lower() == 'quit':
                print("Goodbye!")
                break
            
            if query.lower() == 'dims':
                print("\nDimensions:")
                for dim in self.dimensions:
                    print(f"  {dim['name']}: {dim['negative_pole']} ↔ {dim['positive_pole']} ({dim['variance']*100:.1f}%)")
                print()
                continue
            
            if query.lower() == 'agents':
                print(f"\nKnown agents: {', '.join(sorted(self.agents))}")
                print()
                continue
            
            response = self.chat(query)
            print(f"\nBot: {response}\n")


def create_gearchain_chatbot():
    """Create and initialize the gear chain chatbot."""
    print("═" * 70)
    print(" GEAR CHAIN CHATBOT ".center(70, "═"))
    print(" No LLM for responses - pure gear chain ".center(70))
    print("═" * 70)
    
    chatbot = GearChainChatbot()
    
    base_path = Path(__file__).parent.parent
    sources = [
        (base_path / "truthspace_lcm/gears/corpus/corpus_llm_live.json", "behavioral"),
        (base_path / "truthspace_lcm/gears/corpus/corpus_rich_behavioral.json", "characters"),
        (base_path / "truthspace_lcm/gears/corpus/corpus_knowledge.json", "knowledge"),
        (base_path / "truthspace_lcm/corpus_curated.json", "curated"),
        (base_path / "truthspace_lcm/corpus_holmes_quality.json", "holmes"),
    ]
    
    print("\nLoading knowledge base...")
    for path, name in sources:
        if path.exists():
            chatbot.ingest_corpus(str(path), name)
    
    print("\nLearning dimensions...")
    chatbot.learn_dimensions(min_variance=0.02, max_dims=15)
    
    return chatbot


def main():
    chatbot = create_gearchain_chatbot()
    
    print("\n" + "─" * 70)
    print("TEST QUERIES (no LLM used)")
    print("─" * 70)
    
    test_queries = [
        "Tell me about Holmes",
        "Compare Holmes and Watson",
        "What is similar to villain?",
        "What is the opposite of hero?",
        "Tell me about the king and servant",
    ]
    
    for q in test_queries:
        print(f"\n>>> {q}")
        print(chatbot.chat(q))
    
    print("\n" + "─" * 70)
    chatbot.interactive_chat()
    
    return chatbot


if __name__ == "__main__":
    chatbot = main()
